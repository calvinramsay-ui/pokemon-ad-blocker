// IAB standard ad sizes — used only as a secondary signal, never alone
const IAB_AD_SIZES = new Set([
  '728x90', '970x90', '970x250', '300x250', '300x600',
  '160x600', '120x600', '320x50', '320x100', '300x50',
  '468x60', '336x280', '250x250', '200x200',
]);

// ─── Detection helpers ────────────────────────────────────────────────────────

function isIABSize(el) {
  const w = el.offsetWidth;
  const h = el.offsetHeight;
  if (w < 50 || h < 30) return false;
  return IAB_AD_SIZES.has(`${w}x${h}`);
}

function isAdIframe(el) {
  if (el.tagName !== 'IFRAME') return false;
  const src = el.src || el.getAttribute('src') || '';
  const id = el.id || '';
  return AD_URL_PATTERNS.some(p => p.test(src)) || /^google_ads_iframe/i.test(id);
}

// Strict check for div/section/aside — requires multiple signals
function isAdContainer(el) {
  const tag = el.tagName;
  if (tag === 'IFRAME' || tag === 'INS') return false;

  const id = (el.id || '').toLowerCase();
  const cls = Array.from(el.classList).join(' ').toLowerCase();

  // Strong single signals — unambiguous
  if (/^div-gpt-ad/.test(el.id)) return true;
  if ((el.getAttribute('aria-label') || '').toLowerCase() === 'advertisement') return true;
  if (el.getAttribute('data-ad-slot') || el.getAttribute('data-ad-unit') || el.getAttribute('data-ad-client')) return true;
  if (/^taboola-|^outbrain-/.test(el.id)) return true;

  // Weaker signals: ad-like name + IAB size + actual ad content inside
  const hasAdishName =
    /\b(ad[\-_]?(slot|unit|container|wrapper|banner|placement|frame|zone|box)|advert(?:isement)?|adsense|dfp[\-_]|gpt[\-_]ad)\b/.test(id + ' ' + cls);

  if (hasAdishName && isIABSize(el)) {
    // Must contain an iframe or ins — actual ad markup, not just a styled div
    if (el.querySelector('iframe, ins.adsbygoogle')) return true;
  }

  return false;
}

// Never cover elements that are part of page chrome/nav
function isInsideUI(el) {
  let node = el.parentElement;
  let depth = 0;
  while (node && depth < 6) {
    const tag = node.tagName;
    if (tag === 'NAV' || tag === 'HEADER' || tag === 'FORM' || tag === 'BUTTON') return true;
    const cls = Array.from(node.classList).join(' ').toLowerCase();
    const id = (node.id || '').toLowerCase();
    if (/\b(search|navbar|nav\b|header|menu|toolbar|topbar|masthead)\b/.test(cls + ' ' + id)) return true;
    node = node.parentElement;
    depth++;
  }
  return false;
}

// ─── Pokémon sprite helpers ───────────────────────────────────────────────────

function randomPokemonId() {
  return Math.floor(Math.random() * TOTAL_POKEMON) + 1;
}

function animatedSpriteUrl(id) {
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white/animated/${id}.gif`;
}

function staticSpriteUrl(id) {
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${id}.png`;
}

// ─── Overlay creation ─────────────────────────────────────────────────────────

function createOverlay(adEl) {
  const rect = adEl.getBoundingClientRect();
  if (rect.width < 30 || rect.height < 30) return null;

  const id = randomPokemonId();
  const overlay = document.createElement('div');
  overlay.className = 'pkm-overlay';
  overlay.dataset.pokemonId = id;

  const sx = window.scrollX || window.pageXOffset;
  const sy = window.scrollY || window.pageYOffset;

  Object.assign(overlay.style, {
    position: 'absolute',
    left: `${rect.left + sx}px`,
    top: `${rect.top + sy}px`,
    width: `${rect.width}px`,
    height: `${rect.height}px`,
    zIndex: '2147483646',
    background: 'radial-gradient(ellipse at 40% 40%, #16213e 0%, #0f3460 60%, #1a1a2e 100%)',
    display: 'flex',
    alignItems: 'center',
    justifyContent: 'center',
    flexDirection: 'column',
    overflow: 'hidden',
    borderRadius: '4px',
    border: '2px solid #e63946',
    boxSizing: 'border-box',
    cursor: 'pointer',
    userSelect: 'none',
  });

  // Stars
  for (let i = 0; i < 7; i++) {
    const s = document.createElement('div');
    Object.assign(s.style, {
      position: 'absolute',
      width: `${Math.random() < 0.4 ? 3 : 2}px`,
      height: `${Math.random() < 0.4 ? 3 : 2}px`,
      borderRadius: '50%',
      background: 'white',
      left: `${Math.random() * 100}%`,
      top: `${Math.random() * 100}%`,
      opacity: String(0.3 + Math.random() * 0.7),
      pointerEvents: 'none',
    });
    overlay.appendChild(s);
  }

  // Sprite
  const spriteSize = Math.min(rect.width * 0.55, rect.height * 0.55, 96);
  const img = document.createElement('img');
  img.src = animatedSpriteUrl(id);
  img.onerror = () => { img.src = staticSpriteUrl(id); };
  Object.assign(img.style, {
    width: `${spriteSize}px`,
    height: `${spriteSize}px`,
    objectFit: 'contain',
    imageRendering: 'pixelated',
    filter: 'drop-shadow(0 0 6px rgba(255,215,0,0.7))',
    animation: 'pkmBob 1.6s ease-in-out infinite',
    pointerEvents: 'none',
    flexShrink: '0',
  });
  overlay.appendChild(img);

  // Dex number label
  if (rect.height > 60 && rect.width > 70) {
    const lbl = document.createElement('div');
    lbl.className = 'pkm-label';
    lbl.textContent = `#${String(id).padStart(3, '0')}`;
    Object.assign(lbl.style, {
      color: '#ffd700',
      fontSize: `${Math.min(10, Math.floor(rect.width / 14))}px`,
      fontFamily: 'monospace',
      textShadow: '0 0 4px #000',
      marginTop: '3px',
      pointerEvents: 'none',
      letterSpacing: '0.5px',
    });
    overlay.appendChild(lbl);
  }

  // "AD BLOCKED" badge for larger slots
  if (rect.height > 80 && rect.width > 130) {
    const badge = document.createElement('div');
    badge.textContent = '✕ AD BLOCKED';
    Object.assign(badge.style, {
      position: 'absolute',
      top: '5px',
      right: '5px',
      background: '#e63946',
      color: '#fff',
      fontSize: '7px',
      padding: '2px 5px',
      borderRadius: '3px',
      fontFamily: 'monospace',
      fontWeight: 'bold',
      letterSpacing: '0.5px',
      pointerEvents: 'none',
    });
    overlay.appendChild(badge);
  }

  // Left-click: swap Pokémon
  overlay.addEventListener('click', (e) => {
    e.preventDefault();
    e.stopPropagation();
    swapPokemon(overlay, img);
  });

  // Right-click: release the Pokémon (reveal the ad underneath)
  overlay.addEventListener('contextmenu', (e) => {
    e.preventDefault();
    e.stopPropagation();
    releaseOverlay(adEl, overlay);
  });

  overlay.title = 'Click to swap Pokémon • Right-click to reveal ad';

  return overlay;
}

function swapPokemon(overlay, img) {
  const newId = randomPokemonId();
  overlay.dataset.pokemonId = newId;
  img.src = animatedSpriteUrl(newId);
  img.onerror = () => { img.src = staticSpriteUrl(newId); };
  const lbl = overlay.querySelector('.pkm-label');
  if (lbl) lbl.textContent = `#${String(newId).padStart(3, '0')}`;

  // Quick flash effect
  overlay.style.border = '2px solid #ffd700';
  setTimeout(() => { overlay.style.border = '2px solid #e63946'; }, 300);
}

function releaseOverlay(adEl, overlay) {
  overlay.remove();
  overlayMap.delete(adEl);
  adCount = Math.max(0, adCount - 1);
  reportCount();
}

// ─── Core scan logic ──────────────────────────────────────────────────────────

function injectStyles() {
  if (document.getElementById('pkm-styles')) return;
  const style = document.createElement('style');
  style.id = 'pkm-styles';
  style.textContent = `
    @keyframes pkmBob {
      0%, 100% { transform: translateY(0px); }
      50%       { transform: translateY(-6px); }
    }
    .pkm-overlay:hover {
      box-shadow: 0 0 14px rgba(255, 215, 0, 0.45) !important;
    }
  `;
  (document.head || document.documentElement).appendChild(style);
}

function trycover(el) {
  if (!el || !el.isConnected) return;
  if (coveredAds.has(el)) return;
  if (isInsideUI(el)) return;

  const rect = el.getBoundingClientRect();
  if (rect.width < 30 || rect.height < 30) return;

  const cs = window.getComputedStyle(el);
  if (cs.display === 'none' || cs.visibility === 'hidden' || Number(cs.opacity) === 0) return;

  const overlay = createOverlay(el);
  if (!overlay) return;

  document.body.appendChild(overlay);
  coveredAds.add(el);
  overlayMap.set(el, overlay);
  adCount++;
  reportCount();
}

function scanForAds() {
  if (!enabled || !document.body) return;
  injectStyles();

  // Pass 1: reliable CSS selectors
  AD_SELECTORS.forEach(sel => {
    try { document.querySelectorAll(sel).forEach(trycover); } catch (_) {}
  });

  // Pass 2: all iframes — check src against ad network list
  document.querySelectorAll('iframe').forEach(iframe => {
    if (isAdIframe(iframe)) trycover(iframe);
  });

  // Pass 3: structural containers — strict multi-signal check only
  document.querySelectorAll('div, section, aside').forEach(el => {
    if (!coveredAds.has(el) && isAdContainer(el)) trycover(el);
  });
}

function updatePositions() {
  overlayMap.forEach((overlay, adEl) => {
    if (!adEl.isConnected) {
      overlay.remove();
      overlayMap.delete(adEl);
      adCount = Math.max(0, adCount - 1);
      reportCount();
      return;
    }
    const rect = adEl.getBoundingClientRect();
    const sx = window.scrollX || window.pageXOffset;
    const sy = window.scrollY || window.pageYOffset;
    Object.assign(overlay.style, {
      left: `${rect.left + sx}px`,
      top: `${rect.top + sy}px`,
      width: `${rect.width}px`,
      height: `${rect.height}px`,
    });
  });
}

function removeAllOverlays() {
  document.querySelectorAll('.pkm-overlay').forEach(e => e.remove());
  overlayMap.clear();
  adCount = 0;
  reportCount();
}

function reportCount() {
  try {
    chrome.runtime.sendMessage({ type: 'AD_COUNT', count: adCount });
  } catch (_) {}
}

// ─── Event listeners ──────────────────────────────────────────────────────────

// DOM mutations — catch dynamically injected ads
const observer = new MutationObserver(() => {
  clearTimeout(window._pkmScanTimer);
  window._pkmScanTimer = setTimeout(scanForAds, 500);
});
observer.observe(document.documentElement, { childList: true, subtree: true });

// Reposition on scroll
window.addEventListener('scroll', updatePositions, { passive: true });

// Full reposition on resize
window.addEventListener('resize', () => {
  updatePositions();
  // Re-scan in case new slots were revealed
  clearTimeout(window._pkmResizeTimer);
  window._pkmResizeTimer = setTimeout(scanForAds, 300);
}, { passive: true });

// Staggered scans to catch lazy-loaded / auction-resolved ads
[600, 1800, 3500, 6000, 10000].forEach(ms => setTimeout(scanForAds, ms));
setInterval(scanForAds, 7000);

// ─── Messages from popup ──────────────────────────────────────────────────────
chrome.runtime.onMessage.addListener((msg) => {
  if (msg.type === 'SWAP_ALL') {
    overlayMap.forEach((overlay) => {
      const img = overlay.querySelector('img');
      if (img) swapPokemon(overlay, img);
    });
  }
  if (msg.type === 'RESCAN') {
    scanForAds();
  }
});
