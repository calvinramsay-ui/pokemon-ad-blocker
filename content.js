// Pokémon Ad Blocker v4
// Precise ad detection with no false positives on navigation/UI elements

const TOTAL_POKEMON = 649;
const coveredAds = new WeakSet();
const overlayMap = new Map(); // adElement -> overlay div
let adCount = 0;
let enabled = true;

// ─── Load enabled state from storage ─────────────────────────────────────────
chrome.storage.sync.get({ enabled: true }, (res) => {
  enabled = res.enabled;
  if (enabled) scanForAds();
});

chrome.storage.onChanged.addListener((changes) => {
  if (changes.enabled) {
    enabled = changes.enabled.newValue;
    if (!enabled) {
      removeAllOverlays();
    } else {
      scanForAds();
    }
  }
});

